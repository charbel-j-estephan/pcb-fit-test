// Wraps the CommonJS/UMD libraries we use as plain ES modules in vendor/,
// so the page and its Web Worker load them without a bundler or import map.
// Run after `npm install`: node scripts/vendor.js
import fs from 'node:fs';

const libs = [
  { name: 'clipper', src: 'node_modules/clipper-lib/clipper.js', license: 'Boost Software License 1.0 (Angus Johnson)' },
  { name: 'libtess', src: 'node_modules/libtess/libtess.min.js', license: 'SGI Free Software License B 2.0 (libtess.js by Brendan Kenny)' },
  { name: 'jszip', src: 'node_modules/jszip/dist/jszip.min.js', license: 'MIT or GPLv3 (Stuart Knightley et al.)' },
];

fs.mkdirSync('vendor', { recursive: true });
for (const lib of libs) {
  const pkg = JSON.parse(fs.readFileSync(lib.src.replace(/^(node_modules\/[^/]+)\/.*$/, '$1/package.json'), 'utf8'));
  const code = fs.readFileSync(lib.src, 'utf8');
  const out = `// ${pkg.name}@${pkg.version} — ${lib.license}. Generated by scripts/vendor.js; do not edit.
const module = { exports: {} };
(function (module, exports, define) {
${code}
}).call({}, module, module.exports, undefined);
export default module.exports;
`;
  fs.writeFileSync(`vendor/${lib.name}.js`, out);
  console.log(`vendor/${lib.name}.js  ${pkg.name}@${pkg.version}  ${(out.length / 1024).toFixed(0)} KB`);
}
